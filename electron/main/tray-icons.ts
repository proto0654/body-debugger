import { nativeImage } from 'electron'
import type { NativeImage } from 'electron'
import type { TrayState } from '../../shared/types/events'
import idleFrame from '../resources/tray/idle-0.png?asset'
import soonFrame0 from '../resources/tray/soon-0.png?asset'
import soonFrame1 from '../resources/tray/soon-1.png?asset'
import standupFrame0 from '../resources/tray/standup-0.png?asset'
import standupFrame1 from '../resources/tray/standup-1.png?asset'
import standupFrame2 from '../resources/tray/standup-2.png?asset'
import successFrame0 from '../resources/tray/success-0.png?asset'
import successFrame1 from '../resources/tray/success-1.png?asset'
import successFrame2 from '../resources/tray/success-2.png?asset'
import streakFrame0 from '../resources/tray/streak-0.png?asset'
import streakFrame1 from '../resources/tray/streak-1.png?asset'

/**
 * Tray icon animation frames (CONCEPT.md §13). Generated by
 * `scripts/build-tray-icons.py` as 32×32 PNGs.
 */
export interface TrayFrameSpec {
  /** Image paths in play order. */
  files: string[]
  /** Delay between frames; 0 keeps a single static frame. */
  intervalMs: number
  /** `false` plays the sequence once and holds the last frame. */
  loop: boolean
}

export const TRAY_FRAME_SPECS: Record<TrayState, TrayFrameSpec> = {
  idle: { files: [idleFrame], intervalMs: 0, loop: false },
  soon: { files: [soonFrame0, soonFrame1], intervalMs: 500, loop: true },
  standup: {
    files: [standupFrame0, standupFrame1, standupFrame2],
    intervalMs: 180,
    loop: true
  },
  success: {
    files: [successFrame0, successFrame1, successFrame2],
    intervalMs: 110,
    loop: false
  },
  streak: { files: [streakFrame0, streakFrame1], intervalMs: 600, loop: true }
}

const imageCache = new Map<string, NativeImage>()

function loadImage(path: string): NativeImage {
  const cached = imageCache.get(path)
  if (cached) return cached
  const image = nativeImage.createFromPath(path)
  imageCache.set(path, image)
  return image
}

export function trayFrameSpec(state: TrayState): TrayFrameSpec {
  return TRAY_FRAME_SPECS[state]
}

export function trayFrames(state: TrayState): NativeImage[] {
  return trayFrameSpec(state).files.map(loadImage)
}
